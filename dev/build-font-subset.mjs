// 从当前 UI 文案生成 Noto Sans SC 子集（OFL），供本地自托管；不访问运行时 CDN。
import fs from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const outDir = path.join(root, 'web', 'fonts');
const sources = [
  'web/index.html', 'web/app.js', 'web/routes.mjs', 'web/schedule-page.mjs',
  'web/schedule-model.mjs', 'web/calendar-page.mjs', 'web/calendar-model.mjs',
];

const chars = new Set();
for (const file of sources) {
  const text = await fs.readFile(path.join(root, file), 'utf8');
  for (const ch of text) {
    const cp = ch.codePointAt(0);
    if (cp >= 32 && cp !== 127) chars.add(ch);
  }
}
const text = [...chars].sort().join('');
console.log(`subset chars: ${chars.size}`);

const weights = [400, 600];
const files = [];
for (const weight of weights) {
  const url = `https://fonts.googleapis.com/css2?family=Noto+Sans+SC:wght@${weight}&display=swap&text=${encodeURIComponent(text)}`;
  const css = await fetch(url, {
    headers: { 'user-agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36' },
  }).then((res) => {
    if (!res.ok) throw new Error(`font css ${weight}: HTTP ${res.status}`);
    return res.text();
  });
  const match = css.match(/url\((https:\/\/[^)]+)\)/);
  if (!match) throw new Error(`font css ${weight}: no font url`);
  const bin = Buffer.from(await fetch(match[1], {
    headers: { 'user-agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36' },
  }).then((res) => {
    if (!res.ok) throw new Error(`font file ${weight}: HTTP ${res.status}`);
    return res.arrayBuffer();
  }));
  if (bin.subarray(0, 4).toString('latin1') !== 'wOF2') throw new Error(`font file ${weight}: not woff2`);
  const name = `noto-sans-sc-ui-${weight}.woff2`;
  await fs.writeFile(path.join(outDir, name), bin);
  files.push({ weight, name, bytes: bin.length });
  console.log(`${name}: ${bin.length} bytes`);
}

const licenseUrl = 'https://raw.githubusercontent.com/notofonts/noto-cjk/main/Sans/LICENSE';
const license = await fetch(licenseUrl).then((res) => {
  if (!res.ok) throw new Error(`license: HTTP ${res.status}`);
  return res.text();
});
if (!license.includes('SIL OPEN FONT LICENSE')) throw new Error('license: unexpected content');
await fs.writeFile(path.join(outDir, 'OFL.txt'), license);

await fs.writeFile(path.join(outDir, 'README.txt'), [
  'Noto Sans SC UI subset (generated, do not edit by hand).',
  'Source: Google Fonts / Noto CJK (https://github.com/notofonts/noto-cjk).',
  'License: SIL Open Font License 1.1, see OFL.txt.',
  `Scope: ${chars.size} characters used by web/index.html and web/app.js (weights 400, 600).`,
  'Characters outside this subset fall back to the next family in the CSS stack.',
].join('\n'));

const face = (weight, name) => `@font-face {
  font-family: "Noto Sans SC";
  font-style: normal;
  font-weight: ${weight};
  font-display: swap;
  src: url("./${name}") format("woff2");
}`;
await fs.writeFile(path.join(outDir, 'fonts.css'), [
  '/* Generated by dev/build-font-subset.mjs. Noto Sans SC (OFL), local subset. */',
  ...files.map((f) => face(f.weight, f.name)),
  '',
].join('\n'));
console.log('wrote fonts.css and OFL.txt');
